# nearest whole %). They are effect bundles given by the god's favour tier, not building effects, so the
# building multiplier (OTHER_PRODUCTION_MULTIPLIER) does not reach them. In vanilla: Arinna's, Ptah's and
# Marduk's shrines +5/+8/+12%, Yamm's shrine +5/+8/+10% food from buildings, Levs' shrine +10/+15/+20%,
# Marduk's dwelling +4/+6/+9%. The shrine and dwelling help pages show the same values.
RELIGION_FOOD_PRODUCTION_MULTIPLIER = 2
