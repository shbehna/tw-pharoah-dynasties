"""Confederations at the start of a campaign: a separate mod (mod.json "separate_mods"), not part
of the main pack.

- a campaign script: when a new campaign starts, a human player faction confederates the factions
  that own the regions listed for it in START_CONFEDERATIONS (AI factions only)
"""

from __future__ import annotations

from lib.data import GameData

FEATURE = "confederations"

SCRIPT_PATH = "script/campaign/mod/dynasties_start_confederations.lua"


def build(data: GameData, settings) -> tuple[dict[str, str], list[str]]:
    """The mod's scripts (pack path -> content) and the notes for the change report."""
    s = settings
    factions = {row["key"] for row in data.table("factions_tables").dicts()}
    all_regions = {row["key"] for row in data.table("regions_tables").dicts()}
    for faction, regions in s.START_CONFEDERATIONS.items():
        if faction not in factions:
            raise ValueError(f"START_CONFEDERATIONS: unknown faction {faction}")
        unknown = [region for region in regions if region not in all_regions]
        if unknown:
            raise ValueError(f"START_CONFEDERATIONS ({faction}): unknown regions {unknown}")
    if not s.START_CONFEDERATIONS:
        return {}, []
    notes = [f"New campaigns with {faction} as a human player: it confederates the AI factions that own "
             f"{', '.join(regions)} at the start." for faction, regions in sorted(s.START_CONFEDERATIONS.items())]
    return {SCRIPT_PATH: _script(s)}, notes


def _lua_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _script(s) -> str:
    entries = "\n".join(
        f"\t[{_lua_string(faction)}] = {{ {', '.join(_lua_string(region) for region in regions)} }},"
        for faction, regions in sorted(s.START_CONFEDERATIONS.items())
    )
    log_file = _lua_string(s.START_CONFEDERATIONS_LOG_FILE) if s.START_CONFEDERATIONS_LOG_FILE else "nil"
    return f"""-- Dynasties Start Confederations (separate from Dynasties Rebalance): confederations at the start of a campaign.
-- When a new campaign starts, each faction below that is played by a human confederates the AI
-- factions that own the listed regions (players and rebels are left alone).
-- Generated by generator/features/confederations.py - edit generator/settings/confederations.py instead.

local START_CONFEDERATIONS = {{
{entries}
}}
local LOG_FILE = {log_file}
-- Saved once the confederations are done, so they never run twice in a campaign.
local DONE_KEY = "dynasties_start_confederations_done"

local function log(message)
\tout("[Dynasties Start Confederations] " .. message)
\tif not LOG_FILE then
\t\treturn
\tend
\tlocal file = io.open(LOG_FILE, "a")
\tif file then
\t\tfile:write(os.date("%Y-%m-%d %H:%M:%S") .. "  start confederations: " .. message .. "\\n")
\t\tfile:close()
\tend
end

local function confederate(faction_key, region_keys)
\tlocal faction = cm:get_faction(faction_key)
\tif not faction or faction:is_dead() or not faction:is_human() then
\t\treturn
\tend
\tlocal done = {{}}
\tfor _, region_key in ipairs(region_keys) do
\t\tlocal region = cm:get_region(region_key)
\t\tif not region or region:is_abandoned() then
\t\t\tlog(faction_key .. ": " .. region_key .. " has no owner")
\t\telse
\t\t\tlocal owner = region:owning_faction()
\t\t\tlocal owner_key = owner:name()
\t\t\tif owner_key == faction_key or done[owner_key] then
\t\t\t\t-- Already ours, or confederated for an earlier region.
\t\t\telseif owner:is_human() or owner:is_rebel() then
\t\t\t\tlog(faction_key .. ": " .. region_key .. " belongs to " .. owner_key .. ", which is left alone")
\t\t\telse
\t\t\t\tdone[owner_key] = true
\t\t\t\tcm:force_confederation(faction_key, owner_key)
\t\t\t\tlog(faction_key .. " confederates " .. owner_key .. " (owner of " .. region_key .. ")")
\t\t\tend
\t\tend
\tend
end

cm:add_first_tick_callback_new(function()
\tif cm:get_saved_value(DONE_KEY) then
\t\treturn
\tend
\tcm:set_saved_value(DONE_KEY, true)
\tfor faction_key, region_keys in pairs(START_CONFEDERATIONS) do
\t\tlocal ok, err = pcall(confederate, faction_key, region_keys)
\t\tif not ok then
\t\t\tlog("error: " .. tostring(err))
\t\tend
\tend
end)
"""
