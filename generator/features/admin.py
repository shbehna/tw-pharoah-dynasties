"""Administrative burden.

- administration tier thresholds (script patching the game's script/campaign/supply_points.lua)
- administration cost of main settlement buildings
- administration tiers: bronze and gold upkeep = food upkeep, recruitment cost on every resource,
  construction cost and building upkeep penalties
- administrative buildings that reduce the burden
"""

from __future__ import annotations

import collections
import re

from features import landmarks
from lib.buildings import BEJ, UPKEEP_FACTOR, VALUE_COLUMNS, bonus_value_ui, upkeep_ui_name
from lib.data import Overlay, fmt_float

FEATURE = "admin"

LEGACY_PREFIX = "troy_"  # Troy buildings left in the database but unused by Pharaoh
ADMIN_EFFECT = "troy_effect_building_administration_cost"
SCRIPT_PATH = "script/campaign/mod/dyn_rebal_admin_tiers.lua"
TIER_TITLE = "effect_bundles_localised_title_"
TITLE_RANGE = re.compile(r"\(\d+\s*-\s*\d+\)|\(\d+\+\)")
LEVEL_SUFFIX = re.compile(r"_(\d+)$")
VANILLA_MAJOR = [2, 3, 4, 5, 6]
VANILLA_MINOR = [2, 3, 4]
TIER_BUNDLE = re.compile(r"^phar_map_effect_bundle_supply_points_([a-z_]+)_(\d\d)$")
ADMIN_TIERS = 12
RESOURCES = ["food", "bronze", "gold"]
UPKEEP = {r: f"phar_main_unit_upkeep_cost_percentage_multiplier_mod_{r}" for r in RESOURCES}
RECRUITMENT_COST = {r: f"phar_main_unit_recruitment_cost_percentage_multiplier_mod_{r}" for r in RESOURCES}
# Recruitment cost of every resource for a unit set: Aegea (native units), Canaan, Sea Peoples (horde units).
UNIT_SET_RECRUITMENT_COSTS = [
    "phar_main_recruitment_cost_native_units",
    "phar_sea_recruitment_cost_mod_unit_sets_all_units",
    "phar_sea_recruitment_cost_mod_horde_units",
]
CONSTRUCTION_COST = "phar_main_building_construction_cost_percentage_multiplier_mod_all"
BUILDING_UPKEEP = "dyn_rebal_building_upkeep_percentage_mod_"  # + resource; new effects
EBEJ = "effect_bundles_to_effects_junctions_tables"


def apply(overlay: Overlay, settings) -> None:
    tiers = _tier_bundles(overlay)
    _thresholds(overlay, settings, tiers)
    _settlement_costs(overlay, settings)
    _tiers(overlay, settings, tiers)
    _burden_reductions(overlay, settings)


def _tier_bundles(overlay: Overlay) -> dict[str, dict[int, str]]:
    """culture -> tier -> effect bundle key of the administration tiers."""
    tiers: dict[str, dict[int, str]] = collections.defaultdict(dict)
    for row in overlay.rows("effect_bundles_tables"):
        match = TIER_BUNDLE.match(row["key"])
        # script/campaign/supply_points.lua uses tiers 1-12; some cultures have unused empty bundles 13-14.
        if match and int(match.group(2)) <= ADMIN_TIERS:
            tiers[match.group(1)][int(match.group(2))] = row["key"]
    return tiers


def _thresholds(overlay: Overlay, s, tiers: dict[str, dict[int, str]]) -> None:
    thresholds = list(s.ADMIN_TIER_THRESHOLDS)
    if len(thresholds) != ADMIN_TIERS or thresholds[0] != 0 or thresholds != sorted(set(thresholds)):
        raise ValueError(f"ADMIN_TIER_THRESHOLDS needs {ADMIN_TIERS} increasing values starting at 0: {thresholds}")
    if s.ADMIN_BAR_MAX <= thresholds[-1]:
        raise ValueError("ADMIN_BAR_MAX must be above the last tier threshold")
    overlay.put_script(SCRIPT_PATH, _thresholds_script(thresholds, s.ADMIN_BAR_MAX), FEATURE)

    # Tier titles show their range, e.g. "Administration Tier III (110 - 159)". Most cultures
    # reuse the Aegean titles through {{tr:...}}; rewrite every title that has a range.
    loc = overlay.data.loc()
    for bundles in tiers.values():
        for tier, bundle in bundles.items():
            key = TIER_TITLE + bundle
            title = loc.get(key, "")
            if not TITLE_RANGE.search(title):
                continue
            start = thresholds[tier - 1]
            new_range = f"({start} - {thresholds[tier] - 1})" if tier < ADMIN_TIERS else f"({start}+)"
            overlay.put_loc(key, TITLE_RANGE.sub(new_range, title), FEATURE)
    overlay.note(FEATURE, f"Administration tiers start at {', '.join(map(str, thresholds))} points "
                          f"(administration bar up to {s.ADMIN_BAR_MAX}).")


def _thresholds_script(thresholds: list[int], bar_max: int) -> str:
    return f"""-- Dynasties Rebalance: administration tier thresholds.
-- The game defines the tiers in script/campaign/supply_points.lua; instead of replacing that file
-- (which would undo later game fixes to it), this changes its thresholds when the campaign loads.
-- Generated by generator/features/admin.py - edit generator/settings.py instead.

local LOWER_BOUNDS = {{ {', '.join(map(str, thresholds))} }}
local BAR_MAX = {bar_max}

local function patch_admin_tiers()
\tif type(supply_points) ~= "table" or type(supply_points.bounds) ~= "table" then
\t\tout("Dynasties Rebalance: supply_points not loaded, administration tiers unchanged")
\t\treturn false
\tend
\tfor i, lower_bound in ipairs(LOWER_BOUNDS) do
\t\tif supply_points.bounds[i] then
\t\t\tsupply_points.bounds[i].lower_bound = lower_bound
\t\tend
\tend
\tsupply_points.ui.supply_points_max_value = BAR_MAX
\treturn true
end

-- Mod scripts load before the first tick, so the game computes every tier with these thresholds.
patch_admin_tiers()

-- Run by the game's mod loader on the first tick (function named after the file). Moves every
-- faction of a save made without this mod to the tier matching the new thresholds.
function dyn_rebal_admin_tiers()
\tif not patch_admin_tiers() or type(SUPPLY_POINTS_DATA) ~= "table" then
\t\treturn
\tend
\tlocal faction_list = cm:model():world():faction_list()
\tfor i = 0, faction_list:num_items() - 1 do
\t\tlocal faction_name = faction_list:item_at(i):name()
\t\t-- No data yet in a new campaign: the game assigns the tiers itself.
\t\tif type(SUPPLY_POINTS_DATA[faction_name]) == "table" then
\t\t\tsupply_points.apply_effects_for_faction(faction_name)
\t\tend
\tend
end
"""


def settlement_class(building: str):
    """(size, is_province_capital, level) of a main settlement building, or None.

    Main buildings are named in several ways, e.g. ..._main_building_major_<region>_3,
    ..._main_building_food_minor_<region>_2, ..._major_main_building_poc_troy_4,
    ..._major_poc_main_building_<region>_babylon_5.
    """
    tokens = building.split("_")
    match = LEVEL_SUFFIX.search(building)
    if "main_building" not in building or not match or building.startswith(LEGACY_PREFIX):
        return None
    if "major" in tokens:
        size = "major"
    elif "minor" in tokens:
        size = "minor"
    else:
        return None
    return size, "poc" in tokens, int(match.group(1))


def _settlement_costs(overlay: Overlay, s) -> None:
    changes = collections.Counter()
    for row in list(overlay.rows(BEJ)):
        if row["effect"] != ADMIN_EFFECT:
            continue
        found = settlement_class(row["building"])
        if found is None:
            continue
        size, capital, level = found
        table = s.MAJOR_SETTLEMENT_ADMIN_COST if size == "major" else s.MINOR_SETTLEMENT_ADMIN_COST
        vanilla_table = VANILLA_MAJOR if size == "major" else VANILLA_MINOR
        if not 1 <= level <= len(table):
            continue
        extra = 1 if capital else 0
        old_cost = float(row["value"])
        if old_cost != vanilla_table[level - 1] + extra:
            overlay.note(FEATURE, f"Unexpected administration cost {old_cost:g} on {row['building']} "
                                  f"(expected {vanilla_table[level - 1] + extra}); changed anyway.")
        new_cost = table[level - 1] + (extra if s.KEEP_PROVINCE_CAPITAL_EXTRA_ADMIN else 0)
        if old_cost == new_cost:
            continue
        for column in VALUE_COLUMNS:
            row[column] = fmt_float(new_cost)
        overlay.put(BEJ, row, FEATURE)
        label = ("province capital " if capital else "") + size
        changes[(label, level, old_cost, new_cost)] += 1
    for (label, level, old, new), count in sorted(changes.items()):
        overlay.note(FEATURE, f"Administration cost of {count} {label} settlement buildings, level {level}: "
                              f"{old:g} -> {new:g}.")


def _tiers(overlay: Overlay, s, tiers: dict[str, dict[int, str]]) -> None:
    if s.ADMIN_RECRUITMENT_COST is not None and len(s.ADMIN_RECRUITMENT_COST) != ADMIN_TIERS:
        raise ValueError(f"ADMIN_RECRUITMENT_COST needs {ADMIN_TIERS} values: {s.ADMIN_RECRUITMENT_COST}")
    if len(s.ADMIN_BUILDING_UPKEEP) != ADMIN_TIERS:
        raise ValueError(f"ADMIN_BUILDING_UPKEEP needs {ADMIN_TIERS} values: {s.ADMIN_BUILDING_UPKEEP}")
    upkeep_effects = building_upkeep_effects(overlay, s.ADMIN_BUILDING_UPKEEP_RESOURCES)
    for culture, bundles in sorted(tiers.items()):
        for tier, bundle in sorted(bundles.items()):
            if s.ADMIN_BRONZE_GOLD_UPKEEP_EQUALS_FOOD:
                _copy_effect(overlay, bundle, UPKEEP["food"], [UPKEEP["bronze"], UPKEEP["gold"]])
            if s.ADMIN_RECRUITMENT_COST is not None:
                value = s.ADMIN_RECRUITMENT_COST[tier - 1]
                for key in [*RECRUITMENT_COST.values(), *UNIT_SET_RECRUITMENT_COSTS]:
                    row = overlay.get(EBEJ, (bundle, key))
                    if row is not None and float(row["value"]) != value:
                        overlay.put(EBEJ, dict(row, value=value), FEATURE)
            if s.ADMIN_RECRUITMENT_COST_ALL_RESOURCES:
                # Each culture raises the recruitment cost of a single resource; copy it to the others.
                source = next((key for key in RECRUITMENT_COST.values() if overlay.get(EBEJ, (bundle, key))), None)
                if source is not None:
                    _copy_effect(overlay, bundle, source, [key for key in RECRUITMENT_COST.values() if key != source])
            # A 0% penalty is left out: it would only show "+0%" in the tier's tooltip.
            construction = _tier_penalty(s, "ADMIN_BUILDING_COST", tier)
            if construction:
                _put_effect(overlay, bundle, CONSTRUCTION_COST, "faction_to_region_own", construction)
            upkeep = s.ADMIN_BUILDING_UPKEEP[tier - 1]
            if upkeep:
                for effect in upkeep_effects:
                    _put_effect(overlay, bundle, effect, "faction_to_region_own", upkeep)
        parts = []
        if s.ADMIN_BRONZE_GOLD_UPKEEP_EQUALS_FOOD:
            parts.append("bronze and gold upkeep set equal to food upkeep")
        if s.ADMIN_RECRUITMENT_COST_ALL_RESOURCES and any(
                overlay.get(EBEJ, (bundle, key)) for bundle in bundles.values() for key in RECRUITMENT_COST.values()):
            parts.append("food, bronze and gold recruitment cost set equal")
        if s.ADMIN_RECRUITMENT_COST is not None:
            parts.append(f"recruitment cost {', '.join(f'{v:g}' for v in s.ADMIN_RECRUITMENT_COST)}% by tier")
        if s.ADMIN_BUILDING_COST_FIRST_TIER <= ADMIN_TIERS:
            parts.append(f"construction cost {_penalty_text(s, 'ADMIN_BUILDING_COST')}")
        if upkeep_effects and any(s.ADMIN_BUILDING_UPKEEP):
            parts.append(f"{'/'.join(s.ADMIN_BUILDING_UPKEEP_RESOURCES)} building upkeep "
                         f"{', '.join(f'{v:+g}' for v in s.ADMIN_BUILDING_UPKEEP)}% by tier")
        if parts:
            overlay.note(FEATURE, f"Administration tiers ({culture}): {'; '.join(parts)}.")


def _tier_penalty(s, prefix: str, tier: int) -> float:
    """% penalty of `tier` from the settings <prefix>_FIRST_TIER, _START, _STEP and _MAX."""
    first = getattr(s, f"{prefix}_FIRST_TIER")
    if tier < first:
        return 0
    value = getattr(s, f"{prefix}_START") + getattr(s, f"{prefix}_STEP") * (tier - first)
    cap = getattr(s, f"{prefix}_MAX")
    return value if cap is None else min(value, cap)


def _penalty_text(s, prefix: str) -> str:
    cap = getattr(s, f"{prefix}_MAX")
    return (f"+{getattr(s, f'{prefix}_START')}% from tier {getattr(s, f'{prefix}_FIRST_TIER')}, "
            f"+{getattr(s, f'{prefix}_STEP')}% per tier after" + (f" (max {cap}%)" if cap is not None else ""))


def _put_effect(overlay: Overlay, bundle: str, effect: str, scope: str, value: float) -> None:
    overlay.put(EBEJ, {
        "effect_bundle_key": bundle,
        "effect_key": effect,
        "effect_scope": scope,
        "value": value,
        "advancement_stage": "start_turn_completed",
    }, FEATURE)


def building_upkeep_effects(overlay: Overlay, resources: list[str]) -> list[str]:
    """New effects: % building upkeep of each resource (the game has none). Also used by progressive difficulty."""
    factors = {row["resource"]: row["unique_id"] for row in overlay.rows("pooled_resource_factor_junctions_tables")
               if row["factor"] == UPKEEP_FACTOR}
    unknown = sorted(r for r in resources if f"troy_{r}" not in factors)
    if unknown:
        raise ValueError(f"ADMIN_BUILDING_UPKEEP_RESOURCES: unknown resources {unknown}")
    effects = []
    for resource in resources:
        effect = BUILDING_UPKEEP + resource
        icon = f"fx_icon_{resource.removesuffix('s')}_upkeep.png"
        overlay.put("effects_tables", {"effect": effect, "icon": icon, "priority": 100, "icon_negative": icon,
                                       "category": "campaign", "is_positive_value_good": "false"}, FEATURE)
        overlay.put("effect_bonus_value_pooled_resource_factor_junctions_tables", {
            "bonus_value_id": "percentage_multiplier_mod", "effect": effect, "resource_factor": factors[f"troy_{resource}"],
        }, FEATURE)
        overlay.put_loc(f"effects_description_{effect}",
                        f"%+n% to {resource.removesuffix('s')} upkeep of all buildings", FEATURE)
        bonus_value_ui(overlay, f"dyn_rebal_building_upkeep_mod_{resource}", effect,
                       upkeep_ui_name(overlay, f"troy_{resource}", FEATURE), "icon_effect_upkeep.png",
                       percent=True, positive_is_good=False, feature=FEATURE)
        effects.append(effect)
    # The factor's name for a gain; tooltips that still use it would call more upkeep "Building profit".
    overlay.put_loc("pooled_resource_factors_display_name_positive_buildings_upkeep", "Building Upkeep", FEATURE)
    return effects


def _copy_effect(overlay: Overlay, bundle: str, source_key: str, target_keys: list[str]) -> None:
    """Give the effects `target_keys` of `bundle` the value of its effect `source_key`, adding missing ones."""
    source = overlay.get(EBEJ, (bundle, source_key))
    if source is None:
        return
    for key in target_keys:
        target = overlay.get(EBEJ, (bundle, key))
        if target is None:
            overlay.put(EBEJ, dict(source, effect_key=key), FEATURE)
        elif target["value"] != source["value"]:
            overlay.put(EBEJ, dict(target, value=source["value"]), FEATURE)


def _burden_reductions(overlay: Overlay, s) -> None:
    remap = landmarks.remapped_levels(overlay.data)
    levels = {row["level_name"] for row in overlay.rows("building_levels_tables")}
    unknown = sorted(b for b in s.ADMIN_BURDEN_REDUCTIONS if remap.get(b, b) not in levels)
    if unknown:
        raise ValueError(f"ADMIN_BURDEN_REDUCTIONS: unknown building levels {unknown}")
    for building, (full, reduced) in s.ADMIN_BURDEN_REDUCTIONS.items():
        target = remap.get(building, building)
        if target != building:
            overlay.note(FEATURE, f"Burden reduction of {building} applied to {target}, "
                                  f"the landmark level that replaces it.")
        overlay.put(BEJ, {
            "building": target,
            "effect": ADMIN_EFFECT,
            "effect_scope": "building_to_region",
            "value": full,
            "value_damaged": 0,
            "value_ruined": 0,
            "value_low_influence": reduced,
            "value_medium_influence": reduced,
        }, FEATURE)
    overlay.note(FEATURE, f"{len(s.ADMIN_BURDEN_REDUCTIONS)} administrative buildings reduce the administration "
                          f"burden (ADMIN_BURDEN_REDUCTIONS).")
