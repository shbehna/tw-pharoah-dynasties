"""Movement.

- land and naval campaign movement for every faction, on every difficulty
- the naval "Full Speed" stance
- forced march requirement and movement left after razing or sacking an outpost
"""

from __future__ import annotations

from lib.data import Overlay, fmt_float

FEATURE = "movement"

HANDICAPS = "campaign_difficulty_handicap_effects_tables"
EBEJ = "effect_bundles_to_effects_junctions_tables"
ARMY_MOVEMENT = "troy_effect_army_campaign_movement_mod_armies"
FLEET_MOVEMENT = "troy_effect_army_campaign_movement_mod_fleets"
MOVEMENT_RANGE = "troy_effect_army_campaign_movement_range"
STANCE_COST = "troy_effect_army_campaign_stance_ap_cost"
NAVY_FULL_SPEED = "effect_bundle_stance_navy_double_time"
FORCED_MARCH = "effect_bundle_stance_army_forced_march"
SCRIPT_PATH = "script/campaign/mod/dyn_rebal_outpost_sacking.lua"


def apply(overlay: Overlay, settings) -> None:
    s = settings
    # Campaign difficulty handicaps apply to every faction: one row per difficulty, for players and AI.
    difficulties = sorted({int(row["campaign_difficulty_handicap"]) for row in overlay.rows(HANDICAPS)})
    for difficulty in difficulties:
        for human in (True, False):
            for effect, value in ((ARMY_MOVEMENT, s.LAND_MOVEMENT), (FLEET_MOVEMENT, s.NAVAL_MOVEMENT)):
                overlay.put(HANDICAPS, {
                    "campaign_difficulty_handicap": difficulty,
                    "human": human,
                    "effect": effect,
                    "effect_scope": "faction_to_force_own_factionwide",
                    "effect_value": value,
                    "optional_campaign_key": "",
                }, FEATURE)
    overlay.note(FEATURE, f"Campaign movement {s.LAND_MOVEMENT:g}% on land and {s.NAVAL_MOVEMENT:g}% at sea for "
                          f"every faction, player and AI, on every difficulty.")

    full_speed = overlay.get(EBEJ, (NAVY_FULL_SPEED, MOVEMENT_RANGE))
    old_bonus = float(full_speed["value"])
    new_bonus = round(old_bonus * s.NAVAL_FULL_SPEED_BONUS_SCALE, 2)
    full_speed["value"] = fmt_float(new_bonus)
    overlay.put(EBEJ, full_speed, FEATURE)
    overlay.note(FEATURE, f"Full Speed stance bonus +{old_bonus:g}% -> +{new_bonus:g}% (full speed is "
                          f"{100 + s.NAVAL_MOVEMENT + new_bonus:g}% of base instead of {100 + old_bonus:g}%).")

    overlay.put(EBEJ, {
        "effect_bundle_key": FORCED_MARCH,
        "effect_key": STANCE_COST,
        "effect_scope": "army_to_army_own_unseen",
        "value": s.FORCED_MARCH_MIN_MOVEMENT,
        "advancement_stage": "start_turn_completed",
    }, FEATURE)
    overlay.put_script(SCRIPT_PATH, _sacking_script(s), FEATURE)
    overlay.note(FEATURE, f"Forced march needs {s.FORCED_MARCH_MIN_MOVEMENT}% movement left to enter. Armies keep "
                          f"{s.MOVEMENT_LEFT_AFTER_RAZING_OUTPOST:.0%} movement after razing an outpost and "
                          f"{s.MOVEMENT_LEFT_AFTER_SACKING_OUTPOST:.0%} after sacking one (player and AI).")


def _sacking_script(s) -> str:
    return f"""-- Dynasties Rebalance: movement left after razing or sacking an outpost.
-- Generated by generator/features/movement.py - edit generator/settings/movement.py instead.

local MOVEMENT_AFTER_DECISION = {{
\toccupation_decision_ers_raze_without_occupy = {s.MOVEMENT_LEFT_AFTER_RAZING_OUTPOST},
\toccupation_decision_ers_sack = {s.MOVEMENT_LEFT_AFTER_SACKING_OUTPOST},
}}

core:add_listener(
\t"dyn_rebal_outpost_sacking_movement",
\t"CharacterPerformsRegionSlotOccupationDecision",
\ttrue,
\tfunction(context)
\t\tlocal movement = MOVEMENT_AFTER_DECISION[context:occupation_decision_option()]
\t\tif not movement then
\t\t\treturn
\t\tend
\t\tlocal character = context:character()
\t\tlocal military_force = character:military_force()
\t\tif military_force and not military_force:is_null_interface() then
\t\t\tcm:replenish_action_points("character_cqi:" .. character:command_queue_index(), movement)
\t\tend
\tend,
\ttrue
)
"""
