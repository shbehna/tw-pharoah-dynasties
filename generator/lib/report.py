"""Generate docs/CHANGES.md: what the mod changes compared to the game, per section."""

from __future__ import annotations

import collections
import os

from .data import Overlay

DETAIL_LIMIT = 40

TITLES = {
    "admin": "Administrative burden",
    "outposts": "Outposts",
    "movement": "Movement",
    "landmarks": "Landmarks",
    "buildings": "Buildings",
    "garrisons": "Buildings with garrisons",
    "difficulty": "Progressive difficulty",
    "ai": "Campaign AI targets",
    "characters": "Unique characters",
}


def _diff(columns, old, new, key_columns) -> str:
    changes = [f"{c}: {o} → {n}" for c, o, n in zip(columns, old, new) if o != n and c not in key_columns]
    return "; ".join(changes)


def write_report(overlay: Overlay, path: str, features: list[str], prefix: str) -> None:
    lines = [
        "# Changes",
        "",
        "Generated by `generator/generate.py`; do not edit by hand. Lists what the mod changes compared "
        "to the unmodded game, by section of `CHANGELOG.md`.",
        "",
    ]
    notes = collections.defaultdict(list)
    for feature, text in overlay.notes:
        notes[feature].append(text)

    for feature in features:
        lines += [f"## {TITLES.get(feature, feature)}", ""]
        lines += [f"- {text}" for text in notes.get(feature, [])]
        lines.append("")

        summary, details = [], []
        for name, table in sorted(overlay.tables.items()):
            rows = [(k, r) for k, r in table.rows.items() if r.feature == feature]
            if not rows:
                continue
            key_columns = [table.columns[i] for i in table.key_index]
            added = [(k, r) for k, r in rows if overlay.vanilla(name, k) is None]
            changed = [(k, r) for k, r in rows if overlay.vanilla(name, k) is not None]
            summary.append(f"| `{name}` | {len(added)} | {len(changed)} |")
            block = [f"<details><summary><code>{name}</code> — {len(added)} added, {len(changed)} changed</summary>", ""]
            for key, row in changed[:DETAIL_LIMIT]:
                old = list(overlay.vanilla(name, key).values())
                block.append(f"- `{' / '.join(key)}`: {_diff(table.columns, old, row.values, key_columns)}")
            for key, row in added[: max(0, DETAIL_LIMIT - len(changed[:DETAIL_LIMIT]))]:
                values = [f"{c}={v}" for c, v in zip(table.columns, row.values) if c not in key_columns and v != ""]
                block.append(f"- `{' / '.join(key)}` (new): {', '.join(values)[:200]}")
            shown = min(len(rows), DETAIL_LIMIT)
            if len(rows) > shown:
                block.append(f"- … {len(rows) - shown} more in `src/db/{name}/{prefix}{feature}.tsv`")
            block += ["", "</details>", ""]
            details += block
        if summary:
            lines += ["| Table | Added rows | Changed rows |", "| --- | --- | --- |", *summary, ""]
            lines += details
        texts = [key for key, entry in overlay.loc.items() if entry.feature == feature]
        if texts:
            lines += [f"Texts: {len(texts)} entries in `src/text/db/{prefix}{feature}.loc.tsv`.", ""]
        scripts = [p for p, (_c, f) in overlay.scripts.items() if f == feature]
        for script in scripts:
            lines += [f"Script: `src/{script}`.", ""]

    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines).rstrip() + "\n")
